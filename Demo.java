public class Demo {

    public static void main(String[] args) {

        // Integers - short, byte , int , long

        byte a = 5;

        short b = 1200;

        long c = 10000000;

        // Real Values

        float d = 5.6f; // single precision
        double f = 6.72; // double precision. --> standard way

        // Characters

        char x = 'X';

        char y = 'B';

        // boolean

        boolean digit = false;

        System.out.println("Integers" + "byte" + a + "," + "short" + b + "," + "long" + c);

        System.out.println("Reals" + "float" + d + "," + "double" + f);

        System.out.println("Characters" + "x" + "=" + x + "&" + "b" + b);

        System.out.println("boolean" + "digits" + digit);

    }

};